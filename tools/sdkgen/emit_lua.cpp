// mirage_sdkgen: LuaLS annotations for every class, struct and enum (<reference>/lua/<Package>.lua). Definition files
// only (---@meta): never run. They give a Lua mod completion and type checks in an editor, while the runtime itself
// reaches the game through reflection by name (Mirage, steps 3 and 4).
//
// Names: a class is its UnrealScript name (Actor), a struct too (Vector) unless two share it, then it is prefixed with
// its outer class like the C++ SDK (InterpActor_CheckpointRecord); enums the same.

#include "emit.h"

#include <fmt/format.h>

#include <algorithm>
#include <fstream>
#include <map>

namespace sdkgen
{
	namespace
	{
		constexpr std::uint64_t kParm = 0x80, kOutParm = 0x100, kReturnParm = 0x400, kOptionalParm = 0x10;
		constexpr std::uint32_t kFuncStatic = 0x2000;

		class LuaEmitter
		{
		public:
			explicit LuaEmitter(const Model& m) : m_(m)
			{
				// A struct or enum whose name another one has gets the C++ SDK's prefixed name, without the A/U/F
				std::map<std::string, int> count;
				for (const auto& [path, t] : m_.types)
					if (!t.isClass) ++count[t.name];
				for (const auto& [path, t] : m_.types) {
					std::string name = t.name;
					if (!t.isClass && count[t.name] > 1) {
						name = t.cpp;	// "AInterpActor_FCheckpointRecord"
						if (name.size() > 1 && (name[0] == 'A' || name[0] == 'U')) name.erase(0, 1);
						if (const auto at = name.find("_F"); at != std::string::npos) name.erase(at + 1, 1);
					}
					names_[path] = name;
				}
			}

			std::string Package(const std::string& pkg) const
			{
				std::string out = fmt::format("---@meta\n-- Mirage: the {} package's classes, structs and enums for Lua "
											  "(LuaLS annotations).\n-- Generated by mirage_sdkgen from the game's "
											  "packages: don't edit, regenerate (memenu sdk).\n\n", pkg);
				for (const auto& [path, e] : m_.enums) {
					if (e.package != pkg) continue;
					out += fmt::format("-- Enum {}\n---@alias {}\n", path, e.cpp);
					for (std::size_t i = 0; i < e.values.size(); ++i)
						out += fmt::format("---| {} # {}\n", i, e.values[i]);
					out += "\n";
				}
				for (const auto& [path, t] : m_.types) {
					if (t.package != pkg) continue;
					const std::string& name = names_.at(path);
					std::string super;
					if (!t.layout->super.empty())
						if (auto it = names_.find(t.layout->super); it != names_.end()) super = " : " + it->second;
					out += fmt::format("-- {} {}\n---@class {}{}\n", t.isClass ? "Class" : "Struct", path, name, super);
					for (const Property& p : t.layout->properties) {
						std::string type = TypeOf(p.kind, p.typePath, p.innerKind, p.innerPath);
						if (p.arrayDim > 1) type += "[]";
						out += fmt::format("---@field {} {}\n", p.name, type);
					}
					out += fmt::format("local {} = {{}}\n\n", name);
					if (t.isClass) out += Functions(t, name);
				}
				return out;
			}

		private:
			std::string Name(const std::string& path, const char* fallback) const
			{
				const auto it = names_.find(path);
				return it == names_.end() ? fallback : it->second;
			}

			std::string Single(Kind kind, const std::string& path) const
			{
				switch (kind) {
					case Kind::Byte: {
						const Enum* e = m_.EnumAt(path);
						return e ? e->cpp : "integer";
					}
					case Kind::Int: return "integer";
					case Kind::Float: return "number";
					case Kind::Bool: return "boolean";
					case Kind::Object: case Kind::Component: case Kind::Interface: return Name(path, "Object");
					case Kind::Class: return "Class";
					case Kind::Name: case Kind::Str: return "string";
					case Kind::Struct: return Name(path, "table");
					case Kind::Delegate: return "function";
					case Kind::Map: return "table";
					default: return "any";
				}
			}

			std::string TypeOf(Kind kind, const std::string& path, Kind innerKind, const std::string& innerPath) const
			{
				return kind == Kind::Array ? Single(innerKind, innerPath) + "[]" : Single(kind, path);
			}

			std::string Functions(const sdkgen::Type& t, const std::string& name) const
			{
				std::vector<const Struct*> fns = t.functions;
				std::sort(fns.begin(), fns.end(), [](const Struct* a, const Struct* b) { return a->path < b->path; });
				std::string out;
				for (const Struct* f : fns) {
					const std::string fname = f->path.substr(f->path.find_last_of('.') + 1);
					std::vector<std::string> args;
					std::string doc, ret, outs;
					for (const Property& p : f->properties) {
						if (!(p.flags & kParm)) continue;
						const std::string type = TypeOf(p.kind, p.typePath, p.innerKind, p.innerPath);
						if (p.flags & kReturnParm) {
							ret = fmt::format("---@return {}\n", type);
							continue;
						}
						// Out parameters are passed in and also come back, after the return value
						if (p.flags & kOutParm) outs += fmt::format("---@return {} {}\n", type, p.name);
						doc += fmt::format("---@param {}{} {}\n", p.name, p.flags & kOptionalParm ? "?" : "", type);
						args.push_back(p.name);
					}
					std::string list;
					for (std::size_t i = 0; i < args.size(); ++i) list += (i ? ", " : "") + args[i];
					out += doc + ret + outs;
					out += fmt::format("function {}{}{}({}) end\n\n", name, f->functionFlags & kFuncStatic ? "." : ":",
									   fname, list);
				}
				return out;
			}

			const Model& m_;
			std::map<std::string, std::string> names_;	// Lua name by path
		};
	}

	bool EmitLua(const Model& m, const Options& o, std::string& error)
	{
		const std::filesystem::path dir = o.reference / "lua";
		std::error_code ec;
		std::filesystem::remove_all(dir, ec);
		std::filesystem::create_directories(dir, ec);
		if (ec) {
			error = "can't create " + dir.string() + ": " + ec.message();
			return false;
		}
		const LuaEmitter e(m);
		for (const std::string& pkg : m.packages) {
			std::ofstream out(dir / (pkg + ".lua"), std::ios::binary | std::ios::trunc);
			if (!out) {
				error = "can't write " + (dir / (pkg + ".lua")).string();
				return false;
			}
			out << e.Package(pkg);
		}
		return true;
	}
}
